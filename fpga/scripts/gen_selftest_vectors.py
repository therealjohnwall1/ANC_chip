#!/usr/bin/env python3
"""Generate reduced ANC vectors for the FPGA on-chip self-test.

Mirrors chip/dv/gen_anc_vectors.py (same plant, same golden fixed-point
DEFAULT) but emits into fpga/src with a smaller ANC_N so the ROMs fit
comfortably in the XC7Z007S block RAM. Instead of storing every expected
y[n] (64-bit), it folds y[n] into a 64-bit rotate-xor checksum.

Emits:
  fpga/src/mem/x.mem     x codes (ANC_PRIME + ANC_N), 12-bit hex
  fpga/src/mem/e.mem     e codes (ANC_N), 12-bit hex
  fpga/src/mem/w.mem     expected final w[] (TAP_LEN), 16-bit hex
  fpga/src/mem/shat.mem  s_hat[] to load (TAP_LEN), 16-bit hex
  fpga/src/pkg/selftest_params.sv   package: ANC_N, ANC_PRIME, X_LEN, Y_CHK

The hardware checksum recurrence (self_test.sv) is:
    chk <= {chk[62:0], chk[63]} ^ y_n;      // rotate-left-1, then xor
over y[0], y[1], ... y[ANC_N-1] in order.

Run:
  .venv/bin/python fpga/scripts/gen_selftest_vectors.py
  ANC_N=2048 .venv/bin/python fpga/scripts/gen_selftest_vectors.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DV = os.path.join(ROOT, "chip", "dv")
SRC = os.path.abspath(os.path.join(HERE, "..", "src"))
MEM = os.path.join(SRC, "mem")
PKG = os.path.join(SRC, "pkg")
sys.path.insert(0, ROOT)
sys.path.insert(0, DV)

import numpy as np  # noqa: E402

from golden import fmt as F  # noqa: E402
from golden import core as C  # noqa: E402

LR, EPS, TAPS = 0.1, 0.00001, 32
MASK64 = (1 << 64) - 1


def code_to_q15(code: int) -> int:
    """12-bit offset-binary code -> Q1.15 signed 16-bit raw (mirrors sample_in)."""
    msb = (code >> 11) & 1
    sign = 0 if msb else 1
    raw = (sign << 15) | ((code & 0x7FF) << 4)
    return raw - (1 << 16) if raw & 0x8000 else raw


def float_to_code(v: float) -> int:
    """float -> 12-bit offset-binary code (Q1.11, round + saturate)."""
    v = max(-1.0, min(v, 1.0 - 2 ** -11))
    q11 = int(round(v * 2048.0))
    q11 = max(-2048, min(q11, 2047))
    return (q11 + 2048) & 0xFFF


def hexval(raw: int, bits: int) -> str:
    return f"{raw & ((1 << bits) - 1):0{bits // 4}X}"


def wmem(name: str, values, bits: int) -> None:
    with open(os.path.join(MEM, name), "w") as f:
        f.write("\n".join(hexval(v, bits) for v in values) + "\n")
    print(f"wrote {os.path.join(MEM, name)} ({len(values)} entries)")


def main() -> None:
    anc_n = int(os.environ.get("ANC_N", "1024"))
    os.makedirs(MEM, exist_ok=True)
    os.makedirs(PKG, exist_ok=True)

    total = TAPS + anc_n

    # ---- stimulus + plant (identical to gen_anc_vectors.py) ----
    n_idx = np.arange(total)
    x_float = (0.3 * np.sin(2 * np.pi * 300 * n_idx / 16000.0)
               + 0.2 * np.sin(2 * np.pi * 700 * n_idx / 16000.0))
    x_code = np.array([float_to_code(v) for v in x_float], dtype=np.int64)
    xq = np.array([code_to_q15(int(c)) / 32768.0 for c in x_code])

    p_taps = 0.6 * 0.7 ** np.arange(6)
    d = np.convolve(xq, p_taps)[:total]

    s_taps = 0.4 * 0.75 ** np.arange(TAPS)
    s_hat = s_taps.copy()

    from scripts.ans import lms_anc
    _, _, _, e_float, _ = lms_anc(
        xq, d, TAPS, LR,
        s_taps=s_taps, s_hat_taps=s_hat,
        normalize=True, keep_history=False)

    e_code = np.array([float_to_code(float(v)) for v in e_float], dtype=np.int64)

    # ---- golden fixed-point reference ----
    fmt = F.DEFAULT
    s_hat_q15 = [int(np.clip(round(v * 32768.0), -32768, 32767)) for v in s_hat]
    x_q15 = [code_to_q15(int(c)) for c in x_code]
    e_q15 = [code_to_q15(int(c)) for c in e_code]

    s_hat_fxp = [F.from_raw(v, fmt.coef, fmt) for v in s_hat_q15]
    x_fxp = [F.from_raw(v, fmt.sample, fmt) for v in x_q15]
    e_fxp = [F.from_raw(v, fmt.sample, fmt) for v in e_q15]

    st = C.ChipState.init(s_hat_fxp, TAPS, LR, EPS, fmt, w=[0.0] * TAPS)
    st = C.prime(st, x_fxp[:TAPS])

    y_acc = []
    step = max(1, anc_n // 10)
    for j in range(anc_n):
        t = C.sample_step(st, x_fxp[TAPS + j], e_fxp[j])
        y_acc.append(F.raw(t.y.seq.acc))
        st = t.state_out
        if anc_n >= 200 and j % step == 0:
            print(f"  golden {j}/{anc_n}")

    w_final = [F.raw(v) for v in st.w]

    # ---- checksum (must match self_test.sv exactly) ----
    chk = 0
    for y in y_acc:
        chk = (((chk << 1) | (chk >> 63)) & MASK64) ^ (y & MASK64)

    # ---- emit ----
    wmem("x.mem", x_code.tolist(), 12)
    wmem("e.mem", e_code.tolist(), 12)
    wmem("w.mem", w_final, 16)
    wmem("shat.mem", s_hat_q15, 16)

    pkg_path = os.path.join(PKG, "selftest_params.sv")
    with open(pkg_path, "w") as f:
        f.write("// generated by fpga/scripts/gen_selftest_vectors.py -- do not edit\n")
        f.write("package selftest_params;\n")
        f.write(f"  localparam int ANC_N = {anc_n};\n")
        f.write(f"  localparam int ANC_PRIME = {TAPS};\n")
        f.write("  localparam int X_LEN = ANC_N + ANC_PRIME;\n")
        f.write(f"  localparam logic [63:0] Y_CHK = 64'h{chk & MASK64:016X};\n")
        f.write("endpackage\n")
    print(f"wrote {pkg_path} (ANC_N={anc_n}, Y_CHK=0x{chk & MASK64:016X})")


if __name__ == "__main__":
    main()
